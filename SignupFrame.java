    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        String fullname = txtFullname.getText().trim();
    String username = txtUser.getText().trim();
    String email = txtUser1.getText().trim();
    String phone = txtFullname1.getText().trim();
    String address = txtFullname2.getText().trim();

    String pass = new String(txtPass.getPassword());
    String confirm = new String(txtConfirm.getPassword());

    // Check empty fields
    if (fullname.isEmpty()
            || username.isEmpty()
            || email.isEmpty()
            || phone.isEmpty()
            || address.isEmpty()
            || pass.isEmpty()
            || confirm.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please fill in all fields.",
                "Registration",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }
    
    // Validate email
   
// Check email
String[] emailParts = email.split("@", -1);

if (emailParts.length != 2 || emailParts[0].length() < 8
        || !emailParts[1].contains(".")) {

    JOptionPane.showMessageDialog(this,
            "Invalid email address!\n"
            + "Enter at least 8 characters before @.\n"
            + "Example: Lapulapu@gmail.com",
            "Invalid Email",
            JOptionPane.WARNING_MESSAGE);

    txtUser1.requestFocus();
    return;
}


    

// Validate phone number: exactly 11 digits
if (!phone.matches("[0-9]{11}")) {

    JOptionPane.showMessageDialog(
            this,
            "Invalid phone number!\n"
            + "Please enter exactly 11 digits.\n"
            + "Example: 09123456789",
            "Invalid Phone Number",
            JOptionPane.WARNING_MESSAGE
    );

    txtFullname1.requestFocus();
    return;
}

    // Check password
    if (!pass.equals(confirm)) {

        JOptionPane.showMessageDialog(
                this,
                "Passwords do not match.",
                "Registration",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    String sql = "INSERT INTO users "
            + "(fullname, username, email, phone, address, password, role) "
            + "VALUES (?, ?, ?, ?, ?, SHA2(?, 256), 'user')";

    try (
            Connection c = DBConnection.getConnection();
            PreparedStatement ps = c.prepareStatement(sql)
    ) {

        ps.setString(1, fullname);
        ps.setString(2, username);
        ps.setString(3, email);
        ps.setString(4, phone);
        ps.setString(5, address);
        ps.setString(6, pass);

        ps.executeUpdate();

        JOptionPane.showMessageDialog(
                this,
                "Account created successfully!",
                "Registration",
                JOptionPane.INFORMATION_MESSAGE
        );

        new LoginFrame().setVisible(true);
        dispose();

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Registration failed:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }

    }//GEN-LAST:event_btnRegisterActionPerformed

