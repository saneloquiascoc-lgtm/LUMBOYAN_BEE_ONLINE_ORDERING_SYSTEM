    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
    

    int row = tblAllOrders.getSelectedRow();

    // No order selected
    if (row < 0) {
        JOptionPane.showMessageDialog(
            this,
            "Please select an order to delete.",
            "No Order Selected",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Get Order ID from first column
    int orderId = Integer.parseInt(
        tblAllOrders.getValueAt(row, 0).toString()
    );

    // Get customer name for confirmation
    String customer = tblAllOrders.getValueAt(row, 1).toString();

    // Confirmation dialog
    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this order?\n\n"
        + "Order #: " + orderId + "\n"
        + "Customer: " + customer,
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION,
        JOptionPane.WARNING_MESSAGE
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    Connection c = null;

    try {

        c = DBConnection.getConnection();

        // Start transaction
        c.setAutoCommit(false);

        // First delete order items
        String deleteItems =
            "DELETE FROM order_itemss WHERE order_id=?";

        try (PreparedStatement psItems =
                 c.prepareStatement(deleteItems)) {

            psItems.setInt(1, orderId);
            psItems.executeUpdate();
        }

        // Then delete the order
        String deleteOrder =
            "DELETE FROM orderss WHERE id=?";

        try (PreparedStatement psOrder =
                 c.prepareStatement(deleteOrder)) {

            psOrder.setInt(1, orderId);

            int deleted = psOrder.executeUpdate();

            if (deleted == 0) {

                c.rollback();   

                JOptionPane.showMessageDialog(
                    this,
                    "Order could not be found.",
                    "Delete Error",
                    JOptionPane.ERROR_MESSAGE
                );

                return;
            }
        }

        // Save both deletions
        c.commit();

        JOptionPane.showMessageDialog(
            this,
            "Order #" + orderId + " deleted successfully!",
            "Delete Successful",
            JOptionPane.INFORMATION_MESSAGE
        );

        // Refresh table
        loadOrders();

    } catch (Exception e) {

        try {
            if (c != null) {
                c.rollback();
            }
        } catch (Exception rollbackError) {
            rollbackError.printStackTrace();
        }

        JOptionPane.showMessageDialog(
            this,
            "Error deleting order:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );

    } finally {

        try {
            if (c != null) {
                c.setAutoCommit(true);
                c.close();
            }
        } catch (Exception closeError) {
            closeError.printStackTrace();
        }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnPreparingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPreparingActionPerformed
    
    int row = tblAllOrders.getSelectedRow();

    if (row < 0) {
        JOptionPane.showMessageDialog(
            this,
            "Please select an order first.",
            "No Order Selected",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Get the correct order ID, including when Search is active.
    int modelRow = tblAllOrders.convertRowIndexToModel(row);

    int orderId = Integer.parseInt(
        tblAllOrders.getModel().getValueAt(modelRow, 0).toString()
    );

    String sql =
        "UPDATE orderss SET status = 'Preparing' WHERE id = ?";

    try (
        Connection c = DBConnection.getConnection();
        PreparedStatement ps = c.prepareStatement(sql)
    ) {
        ps.setInt(1, orderId);

        int updated = ps.executeUpdate();

        if (updated > 0) {
            JOptionPane.showMessageDialog(
                this,
                "Order #" + orderId + " status changed to Preparing."
            );

            loadOrders();

            sorter.setModel(
                (DefaultTableModel) tblAllOrders.getModel()
            );
        } else {
            JOptionPane.showMessageDialog(
                this,
                "Order not found."
            );
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(
            this,
            "Error updating order status:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnPreparingActionPerformed

