private void loadOrders() {

    DefaultTableModel m = new DefaultTableModel(
        new Object[]{
            "Order #",
            "Customer",
            "Product",
            "Qty",
            "Address",
            "Phone",
            "Total",
            "Status",
            "Date",
            "Payment Method",
            "Payment Status",
            
                
        },
        0
    );

    tblAllOrders.setModel(m);

    String sql =
    "SELECT o.id, " +
    "COALESCE(u.fullname, 'Unknown Customer') AS fullname, " +
    "COALESCE(oi.product_name, 'No item') AS product, " +
    "COALESCE(oi.qty, 0) AS qty, " +
    "o.address, o.phone, o.total, o.status, o.order_date, " +
    "o.payment_method, o.payment_status " +
    "FROM orderss o " +
    "LEFT JOIN users u ON o.user_id = u.id " +
    "LEFT JOIN order_itemss oi ON o.id = oi.order_id " +
    "ORDER BY o.id DESC, oi.id ASC";

    try (
        Connection c = DBConnection.getConnection();
        PreparedStatement ps = c.prepareStatement(sql);
        ResultSet rs = ps.executeQuery()
    ) {

        while (rs.next()) {

            
            m.addRow(new Object[]{
    rs.getInt("id"),
    rs.getString("fullname"),
    rs.getString("product"),
    rs.getInt("qty"),
    rs.getString("address"),
    rs.getString("phone"),
    String.format("₱ %.2f", rs.getDouble("total")),
    rs.getString("status"),
    rs.getTimestamp("order_date"),
    rs.getString("payment_method"),
    rs.getString("payment_status")
});
        }

        // Make Customer and Product columns wider.
        tblAllOrders.getColumnModel()
            .getColumn(1).setPreferredWidth(180);

        tblAllOrders.getColumnModel()
            .getColumn(2).setPreferredWidth(220);

        tblAllOrders.getColumnModel()
            .getColumn(4).setPreferredWidth(160);

        tblAllOrders.getColumnModel()
            .getColumn(8).setPreferredWidth(150);

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this,
            "Error loading orders:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}

   
private void setupSearch() {
    sorter = new TableRowSorter<>(
        (DefaultTableModel) tblAllOrders.getModel()
    );

    tblAllOrders.setRowSorter(sorter);

    jTextField1.getDocument().addDocumentListener(
        new DocumentListener() {

            @Override
            public void insertUpdate(DocumentEvent e) {
                searchCustomer();
                
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                searchCustomer();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                searchCustomer();
            }
        }
    );
}

private void searchCustomer() {
     String keyword = jTextField1.getText().trim();

    if (sorter == null) {
        return;
    }

    if (keyword.isEmpty()) {
        sorter.setRowFilter(null);
    } else {
        // Search all columns, including Status.
        sorter.setRowFilter(
            RowFilter.regexFilter(
                "(?i)" + java.util.regex.Pattern.quote(keyword)
            )
        );
    }
}


