public MyOrdersFrame() {
    initComponents();

    setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);

    DefaultTableModel m = new DefaultTableModel(
        new Object[]{
            "Order #",
            "Product Name",
            "Quantity",
            "Total",
            "Status",
            "Address",
            "Phone",
            "Date"
        },
        0
    );

    tblOrders.setModel(m);

    String sql =
        "SELECT o.id AS order_id, " +
        "COALESCE(oi.product_name, 'No item') AS product_name, " +
        "COALESCE(oi.qty, 0) AS quantity, " +
        "o.total, o.status, o.address, o.phone, o.order_date " +
        "FROM orderss o " +
        "LEFT JOIN order_itemss oi ON o.id = oi.order_id " +
        "WHERE o.user_id = ? " +
        "ORDER BY o.id DESC, oi.id ASC";

    try (
        Connection c = DBConnection.getConnection();
        PreparedStatement ps = c.prepareStatement(sql)
    ) {
        ps.setInt(1, Session.userId);

        try (ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                m.addRow(new Object[]{
                    rs.getInt("order_id"),
                    rs.getString("product_name"),
                    rs.getInt("quantity"),
                    String.format("₱ %.2f", rs.getDouble("total")),
                    rs.getString("status"),
                    rs.getString("address"),
                    rs.getString("phone"),
                    rs.getTimestamp("order_date")
                });
            }
        }

        // Make the columns easier to read.
        tblOrders.getColumnModel().getColumn(0).setPreferredWidth(80);
        tblOrders.getColumnModel().getColumn(1).setPreferredWidth(220);
        tblOrders.getColumnModel().getColumn(2).setPreferredWidth(80);
        tblOrders.getColumnModel().getColumn(5).setPreferredWidth(180);
        tblOrders.getColumnModel().getColumn(7).setPreferredWidth(150);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(
            this,
            "Error loading orders:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}

