    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
   
        
    String username = txtUser.getText().trim();
    String password = new String(txtPass.getPassword());

    // Check empty fields
    if (username.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter your username and password.",
            "Login",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql = "SELECT id, fullname, email, phone, address, role "
               + "FROM users "
               + "WHERE username = ? "
               + "AND password = SHA2(?, 256)";

    try (
        Connection c = DBConnection.getConnection();
        PreparedStatement ps = c.prepareStatement(sql)
    ) {

        ps.setString(1, username);
        ps.setString(2, password);

        ResultSet rs = ps.executeQuery();

        if (rs.next()) {

            // Save logged-in user's information
            Session.userId = rs.getInt("id");
            Session.fullname = rs.getString("fullname");
            Session.email = rs.getString("email");
            Session.phone = rs.getString("phone");
            Session.address = rs.getString("address");
            Session.role = rs.getString("role");

            JOptionPane.showMessageDialog(
                this,
                "Login Successful!",
                "Login",
                JOptionPane.INFORMATION_MESSAGE
            );

            // Open based on role
            if ("admin".equalsIgnoreCase(Session.role)) {

                new AdminFrame().setVisible(true);

            } else {

                new ShopFrame().setVisible(true);
            }

            // Close login
            dispose();

        } else {

            JOptionPane.showMessageDialog(
                this,
                "Invalid username or password.",
                "Login Failed",
                JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this,
            "Database error:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }

    
    }//GEN-LAST:event_btnLoginActionPerformed

